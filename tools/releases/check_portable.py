#!/usr/bin/env python3
"""Test an extracted native launcher, then inventory only a successful build."""
import argparse
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys
import time
import xml.etree.ElementTree as ET

from inventory import digest_file, inventory
from prepare_preview import sha


def summarize_tests(root, output):
    totals = {'tests': 0, 'failures': 0, 'errors': 0, 'skipped': 0, 'suites': 0}
    for path in root.glob('*/target/surefire-reports/TEST-*.xml'):
        suite = ET.parse(path).getroot()
        totals['suites'] += 1
        for key in ('tests', 'failures', 'errors', 'skipped'):
            totals[key] += int(suite.get(key, '0'))
    if not totals['suites'] or totals['failures'] or totals['errors']:
        raise ValueError('A complete passing Maven test run is required')
    output.write_text(json.dumps(totals, indent=2) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--work', type=Path, required=True)
    parser.add_argument('--version', required=True)
    parser.add_argument('--os', choices=['windows', 'macos'], required=True)
    parser.add_argument('--arch', choices=['x64', 'arm64'], required=True)
    parser.add_argument('--summarize-only', action='store_true')
    args = parser.parse_args()
    root, work = args.root.resolve(), args.work.resolve()
    if args.summarize_only:
        summarize_tests(root, work / 'tests.json')
        return 0
    machine = platform.machine().lower()
    actual_arch = 'arm64' if machine in ('arm64', 'aarch64') else 'x64' if machine in ('amd64', 'x86_64') else machine
    actual_os = 'windows' if sys.platform == 'win32' else 'macos' if sys.platform == 'darwin' else sys.platform
    if (actual_os, actual_arch) != (args.os, args.arch):
        raise ValueError('Native runner architecture does not match artifact target')
    archives = list((root / 'packaging/dist').glob('vibecraft-*-with-data.*'))
    if len(archives) != 1:
        raise ValueError('Exactly one complete portable archive is required')
    archive = archives[0]
    relocated = work / 'relocated archive with spaces'
    relocated.mkdir()
    # This archive was generated by this job from jpackage, not a remote input.
    shutil.unpack_archive(str(archive), str(relocated))
    if args.os == 'windows':
        launcher = relocated / 'Vibecraft/Vibecraft.exe'
        app = relocated / 'Vibecraft/app'
        java = relocated / 'Vibecraft/runtime/bin/java.exe'
    else:
        launcher = relocated / 'Vibecraft.app/Contents/MacOS/Vibecraft'
        app = relocated / 'Vibecraft.app/Contents/app'
        java = relocated / 'Vibecraft.app/Contents/runtime/Contents/Home/bin/java'
    db = app / 'data/wowforever.sqlite'
    before = sha(db)
    env = os.environ.copy()
    for key in ('JAVA_HOME', 'JRE_HOME', 'JAVA_TOOL_OPTIONS', 'JDK_JAVA_OPTIONS', '_JAVA_OPTIONS', 'CLASSPATH'):
        env.pop(key, None)
    env['PATH'] = str(work / 'no-tools-here')
    for key in ('XDG_DATA_HOME', 'XDG_CACHE_HOME', 'XDG_CONFIG_HOME', 'APPDATA', 'LOCALAPPDATA'):
        target = work / 'fresh-user' / key.lower()
        target.mkdir(parents=True)
        env[key] = str(target)
    started = time.time()
    result = subprocess.run([str(launcher), '--self-test'], env=env, cwd=work,
                            capture_output=True, text=True, timeout=180)
    (work / 'native-self-test.log').write_text(result.stdout + result.stderr)
    expected = 'items=32136 npcs=13392 instances=37 build_id=40ca42c8e8c6442c0e2e633f76bf4f4638ebf23faf4029b568ee1ee038c207b7'
    if result.returncode or expected not in result.stdout + result.stderr or sha(db) != before:
        raise ValueError('Actual relocated native launcher self-test failed or changed the DB')
    runtime = subprocess.run([str(java), '-version'], capture_output=True, text=True, check=True, timeout=30)
    (work / 'runtime-version.log').write_text(runtime.stdout + runtime.stderr)
    report = {'result': 'passed', 'os': args.os, 'arch': args.arch,
              'launcher': str(launcher.relative_to(work)), 'elapsed_seconds': round(time.time() - started, 2),
              'path_has_no_tools': True, 'manual_jvm_properties': False,
              'database_unchanged': True, 'fresh_user_directories': True,
              'gui_visual_acceptance': 'not-run', 'signing': 'unsigned',
              'native_package_version': '1.4.1' if args.os == 'macos' else '0.4.1'}
    (work / 'native-launch.json').write_text(json.dumps(report, indent=2) + '\n')
    commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=root, text=True).strip()
    spec = {'version': args.version, 'source_commit': commit,
            'database': {'path': str(db), 'sha256': before,
                         'build_id': '40ca42c8e8c6442c0e2e633f76bf4f4638ebf23faf4029b568ee1ee038c207b7',
                         'product': 'wow_classic_beta'},
            'evidence': [{'name': 'Maven full verification', 'result': 'passed', 'path': str(work / 'tests.json')},
                         {'name': 'Relocated native launcher self-test', 'result': 'passed', 'path': str(work / 'native-launch.json')},
                         {'name': 'Native self-test output', 'result': 'passed', 'path': str(work / 'native-self-test.log')},
                         {'name': 'Bundled Java runtime', 'result': 'passed', 'path': str(work / 'runtime-version.log')},
                         {'name': 'Interactive visual acceptance', 'result': 'not-run', 'reason': 'Requires manual platform review'}],
            'artifacts': [{'path': str(archive), 'os': args.os, 'arch': args.arch,
                           'includes_database': True, 'bundled_java': True,
                           'java_version': (runtime.stdout + runtime.stderr).splitlines()[0],
                           'launch_test': 'passed', 'launch_evidence_index': 1}]}
    final = inventory(spec, work)
    upload = work / 'upload'
    upload.mkdir()
    shutil.copy2(archive, upload / archive.name)
    (upload / 'manifest.json').write_text(json.dumps(final, indent=2) + '\n')
    entry = final['artifacts'][0]
    (upload / 'SHA256SUMS').write_text(f"{entry['sha256']}  {entry['filename']}\n")
    for name in ('tests.json', 'native-launch.json', 'native-self-test.log', 'runtime-version.log'):
        shutil.copy2(work / name, upload / name)
    print('Native self-test passed; only complete archive and bounded evidence staged for manual workflow artifact upload.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
